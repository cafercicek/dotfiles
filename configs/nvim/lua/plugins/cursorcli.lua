-- Cursor CLI agent inside Neovim (interactive mode only; Quick Edit not mapped).
return {
  "suiramdev/cursorcli.nvim",
  cmd = {
    "CursorCliOpen",
    "CursorCliOpenWithLayout",
    "CursorCliToggle",
    "CursorCliClose",
    "CursorCliResume",
    "CursorCliRestart",
    "CursorCliNew",
    "CursorCliSelect",
    "CursorCliRename",
    "CursorCliListSessions",
    "CursorCliAddSelection",
    "CursorCliFixErrorAtCursor",
    "CursorCliFixErrorAtCursorInNewSession",
    "CursorCliAddVisualSelectionToNewSession",
  },
  opts = {
    command = { "agent" },
    auto_insert = true,
    notify = true,
    path = { relative_to_cwd = true },
    position = "float",
    split_size = 0.4,
    float = {
      width = 0.9,
      height = 0.8,
      border = "rounded",
      title = " Cursor Agent ",
    },
  },
  keys = {
    { "<leader>ai", "<Cmd>CursorCliToggle<CR>", desc = "Cursor Agent toggle", mode = "n" },
    { "<leader>af", "<Cmd>CursorCliOpenWithLayout float<CR>", desc = "Cursor Agent (float)", mode = "n" },
    { "<leader>av", "<Cmd>CursorCliOpenWithLayout vsplit<CR>", desc = "Cursor Agent (vsplit)", mode = "n" },
    { "<leader>ah", "<Cmd>CursorCliOpenWithLayout hsplit<CR>", desc = "Cursor Agent (hsplit)", mode = "n" },
    { "<leader>ac", function() require("cursorcli").close() end, desc = "Cursor Agent close", mode = "n" },
    { "<leader>an", function() require("cursorcli").new_chat() end, desc = "Cursor Agent new chat", mode = "n" },
    { "<leader>at", function() require("cursorcli").select_chat() end, desc = "Cursor Agent select chat", mode = "n" },
    { "<leader>aR", function() require("cursorcli").resume() end, desc = "Cursor Agent resume", mode = "n" },
    { "<leader>ax", function() require("cursorcli").restart() end, desc = "Cursor Agent restart", mode = "n" },
    { "<leader>al", function() require("cursorcli").list_sessions() end, desc = "Cursor Agent list sessions", mode = "n" },
    { "<leader>ae", function() require("cursorcli").request_fix_error_at_cursor() end, desc = "Cursor Agent fix error", mode = "n" },
    { "<leader>aa", function() require("cursorcli").add_visual_selection() end, desc = "Cursor Agent add selection", mode = "x" },
    {
      "<leader>aA",
      function() require("cursorcli").request_fix_error_at_cursor_in_new_session() end,
      desc = "Cursor Agent fix error (new session)",
      mode = "n",
    },
    {
      "<leader>aA",
      function() require("cursorcli").add_visual_selection_to_new_session() end,
      desc = "Cursor Agent selection (new session)",
      mode = "x",
    },
  },
}
